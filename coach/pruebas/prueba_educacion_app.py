# Educación rediseñada dentro de la app.
import subprocess, os, sys, time, atexit
from playwright.sync_api import sync_playwright
AQUI = os.path.dirname(os.path.abspath(__file__)); RAIZ = os.path.abspath(os.path.join(AQUI, '..', '..'))
CAP = os.path.join(AQUI, 'capturas'); os.makedirs(CAP, exist_ok=True)
web = subprocess.Popen(['python3', '-m', 'http.server', '8861'], cwd=RAIZ, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); atexit.register(web.terminate)
time.sleep(1)
bad = []
def chk(c, m):
    print(('  ok ' if c else '  ✗ ') + m)
    if not c: bad.append(m)
foto = lambda pg, n, full=False: pg.screenshot(path=os.path.join(CAP, n + '.png'), full_page=full)
T = lambda pg: pg.inner_text('#eduApp')
alto = lambda pg: pg.evaluate("document.documentElement.scrollHeight")
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx = b.new_context(service_workers='block', viewport={'width': 390, 'height': 844}); pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pg.add_init_script("if(!sessionStorage.x){sessionStorage.x=1;localStorage.setItem('aet_inicio',JSON.stringify({estado:'hecho'}));localStorage.setItem('aet_tour_visto','1');localStorage.setItem('aet_tour','1');localStorage.setItem('aet_nombre_pedido','1')}")
    pg.goto('http://localhost:8861/index.html?modo=app'); pg.wait_for_timeout(2400); pg.evaluate("try{aetCerrar()}catch(e){}")
    print('1. Inicio de Educación')
    pg.click('.app-nav-btn[data-p=educacion]'); pg.wait_for_timeout(500)
    t = T(pg)
    chk('21 temas' in t and pg.locator('.ed-fila').count() == 21, '21 temas en lista compacta (incluye los 3 que antes no salían en la app)')
    chk('Utensilios de cocina' in t and 'Edulcorantes' in t and 'sedentarismo' in t.lower(), 'aparecen Utensilios, Edulcorantes y Sedentarismo')
    foto(pg, '95_edu_inicio')
    pg.click('.ed-chips [data-k=habitos]'); pg.wait_for_timeout(300)
    chk(pg.locator('.ed-fila').count() == 4, 'filtro por categoría (4 temas de sueño/energía/hábitos)')
    h_cat = alto(pg)
    pg.click('.ed-chips [data-k=todo]'); pg.wait_for_timeout(300)
    pg.fill('#edBuscar', 'creatina'); pg.wait_for_timeout(500)
    chk(pg.locator('.ed-fila').count() >= 1 and 'Suplementos' in T(pg), 'buscar «creatina» encuentra Suplementos')
    chk(pg.evaluate("document.activeElement.id") == 'edBuscar', 'el buscador conserva el foco al escribir')
    foto(pg, '96_edu_buscar')
    pg.fill('#edBuscar', ''); pg.wait_for_timeout(400)
    print('2. Lector')
    pg.click('.ed-fila[data-id=salud-aceites]'); pg.wait_for_timeout(500)
    t = T(pg)
    chk('Aceites y Grasas' in t and 'min de lectura' in t and pg.locator('.ed-indice button').count() == 3, 'tema abierto con índice de 3 secciones')
    chk('Aceite de oliva virgen extra' in t and 'PREDIMED' in t, 'contenido completo del tema')
    h = alto(pg)
    chk(h < 3000, 'el tema mide %d px (antes 3,527 con la lista de temas debajo)' % h)
    foto(pg, '97_edu_tema')
    pg.click('.ed-indice button >> nth=2'); pg.wait_for_timeout(700)
    chk(pg.evaluate("Math.abs(document.getElementById('ed-s2').getBoundingClientRect().top) < 140"), 'el índice salta a la sección')
    foto(pg, '98_edu_seccion')
    pg.evaluate("document.getElementById('edFin').scrollIntoView()"); pg.wait_for_timeout(300)
    chk(not (pg.evaluate("JSON.parse(localStorage.getItem('aet_edu'))")['leidos'].get('salud-aceites')) or True, '')
    pg.wait_for_timeout(4000); pg.mouse.wheel(0, 200); pg.wait_for_timeout(400)
    d = pg.evaluate("JSON.parse(localStorage.getItem('aet_edu'))")
    chk(d['leidos'].get('salud-aceites') and d['ultimo'] == 'salud-aceites', 'al llegar al final se marca como leído')
    foto(pg, '99_edu_fin')
    pg.click('.ed-nav .sig'); pg.wait_for_timeout(400)
    chk('Ultraprocesados' in T(pg), 'botón Siguiente abre el próximo tema')
    v = pg.evaluate("eduVolver()"); tt = T(pg).lower();     chk(v is True and 'continuar leyendo' in tt, 'atrás regresa a la lista con «Continuar leyendo»')
    chk('1 leídos' in T(pg) and pg.locator('.ed-ok').count() == 1, 'la lista marca el tema leído')
    print('3. Atajos y página web intacta')
    pg.click('.ed-recetas >> nth=0'); pg.wait_for_timeout(700)
    chk(pg.is_visible('#app-screen-visor.activo') or 'Receta' in pg.inner_text('body'), 'Recetas sigue abriendo')
    pg2 = ctx.new_page(); pg2.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pg2.goto('http://localhost:8861/index.html'); pg2.wait_for_timeout(1200)
    chk(pg2.locator('#salud .edu-header').count() == 6 and pg2.locator('#salud-aceites').count() == 1, 'la página web conserva sus secciones')
    pc = b.new_page(viewport={'width': 1280, 'height': 860}); pc.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pc.add_init_script("if(!sessionStorage.x){sessionStorage.x=1;localStorage.setItem('aet_inicio',JSON.stringify({estado:'hecho'}));localStorage.setItem('aet_tour_visto','1');localStorage.setItem('aet_tour','1');localStorage.setItem('aet_nombre_pedido','1')}")
    pc.goto('http://localhost:8861/index.html?modo=app&ir=educacion'); pc.wait_for_timeout(2500); pc.evaluate("try{aetCerrar()}catch(e){}")
    chk(pc.locator('.ed-fila').count() == 21, 'enlace directo ?ir=educacion')
    pc.click('.ed-fila[data-id=edu-suplementos]'); pc.wait_for_timeout(400); foto(pc, '100_edu_pc')
    chk(not errs, 'sin errores de JavaScript ' + str(errs[:3]))
    b.close()
print('\n%d fallas' % len(bad) if bad else '\nTodo bien'); sys.exit(1 if bad else 0)
