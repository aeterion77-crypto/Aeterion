# Página web por secciones (como la app). Revisa rutas, enlaces viejos, pestañas, Educación web y que la app no cambie.
import subprocess, os, sys, time, atexit
from playwright.sync_api import sync_playwright
AQUI = os.path.dirname(os.path.abspath(__file__)); RAIZ = os.path.abspath(os.path.join(AQUI, '..', '..'))
CAP = os.path.join(AQUI, 'capturas'); os.makedirs(CAP, exist_ok=True)
web = subprocess.Popen(['python3', '-m', 'http.server', '8862'], cwd=RAIZ, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); atexit.register(web.terminate)
time.sleep(1)
bad = []
def chk(c, m):
    print(('  ok ' if c else '  ✗ ') + m)
    if not c: bad.append(m)
foto = lambda pg, n, full=False: pg.screenshot(path=os.path.join(CAP, n + '.png'), full_page=full)
vis = lambda pg, i: pg.evaluate("(i)=>{const e=document.getElementById(i);return !!e && e.offsetHeight>0}", i)
alto = lambda pg: pg.evaluate("document.documentElement.scrollHeight")
def ir(pg, h): pg.evaluate("(h)=>location.hash=h", h); pg.wait_for_timeout(400)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    for ancho, alto_v, n in [(1366, 860, 'pc'), (390, 844, 'movil')]:
        print('== ' + n)
        pg = b.new_page(viewport={'width': ancho, 'height': alto_v}); errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
        pg.goto('http://localhost:8862/index.html'); pg.wait_for_timeout(2000)
        chk(vis(pg, 'hero') and vis(pg, 'webInicio') and not vis(pg, 'productos') and not vis(pg, 'salud'), 'inicio: portada + tarjetas, nada más')
        chk(alto(pg) < (5000 if n == 'pc' else 7200), 'inicio mide %d px (antes %d)' % (alto(pg), 17779 if n == 'pc' else 29550))
        chk(pg.locator('.wb-anuncio').count() == 1 and pg.locator('.wb-confianza > div').count() == 5 and pg.locator('.wb-prod').count() == 3, 'tienda: aviso de envíos, 5 sellos de confianza, 3 productos')
        chk(pg.inner_text('.wb-precio[data-id=creatina]') == '$480 MXN' and pg.is_visible('.wb-hero-img img'), 'precio real y foto de portada')
        pg.click('.wb-prod .btn-agregar >> nth=0'); pg.wait_for_timeout(500)
        chk(pg.inner_text('#wbCarritoN') == '1', 'agregar desde la portada suma al carrito de la cabecera')
        pg.evaluate("try{cerrarCarrito()}catch(e){document.querySelectorAll('.carrito-overlay,#carrito-overlay').forEach(x=>x.click())}"); pg.wait_for_timeout(300)
        if n == 'movil': pg.click('.wb-ibtn-buscar'); pg.wait_for_timeout(200)
        pg.fill('#wbBuscar', 'ayuno'); pg.wait_for_timeout(300)
        chk('Ayuno Intermitente' in pg.inner_text('#wbBuscarRes'), 'el buscador encuentra temas')
        pg.press('#wbBuscar', 'Enter'); pg.wait_for_timeout(500)
        chk('Ayuno Intermitente' in pg.inner_text('#webEdu'), 'Enter abre el primer resultado')
        pg.evaluate('eduVolver()'); ir(pg, '#/inicio')
        foto(pg, '101_web_inicio_' + n, n == 'movil')
        menu = pg.evaluate("[...document.querySelectorAll('#nav .nav-links a')].map(a=>a.textContent.trim())")
        chk(menu == ['Inicio', 'Productos', 'Programas', 'Educación', 'Nosotros', 'Abrir app'], 'menú de 5 secciones + Abrir app')
        pg.click('.wb-tit a[href="#/productos"]'); pg.wait_for_timeout(400)
        chk(vis(pg, 'productos') and not vis(pg, 'laboratorio') and not vis(pg, 'hero') and pg.locator('#webCab .wb-tabs a').count() == 4, 'Productos con 4 pestañas, solo una visible')
        foto(pg, '102_web_productos_' + n)
        pg.click('#webCab .wb-tabs a >> nth=1'); pg.wait_for_timeout(400)
        chk(vis(pg, 'laboratorio') and not vis(pg, 'productos') and pg.evaluate("window.scrollY") < 5, 'pestaña Laboratorio, arriba de la página')
        ir(pg, '#/inicio'); chk(pg.evaluate("(()=>{const g=document.querySelector('#webInicio .wb-grid'),b=document.querySelector('.my-banda2');return !!b&&g.nextElementSibling===b})()"), 'banda de mayoreo grande justo debajo de «Todo lo que encuentras»'); pg.click('.my-banda2 a.btn-outline'); pg.wait_for_timeout(400)
        t = pg.inner_text('#mayoreo')
        chk(vis(pg, 'mayoreo') and '$5,000' in t and '50%' in t and 'Premium' in t, 'Mayoreo: compra mínima $5,000 y 50% en Premium')
        chk(not any(x in t for x in ['$260', '$270', '$180', '$399', '$449', '$299', 'Le cuesta', 'Gana']), 'Mayoreo no muestra precios ni ganancias')
        chk(pg.locator('#mayoreo a.my-wa').count() == 2 and all(h.startswith('https://wa.me/525613241969?text=') for h in pg.eval_on_selector_all('#mayoreo a.my-wa', 'e=>e.map(a=>a.href)')), 'botones directo a WhatsApp')
        foto(pg, '105_web_mayoreo_' + n, True)
        ir(pg, '#contacto')
        chk(vis(pg, 'contacto') and 'Nosotros' in pg.inner_text('#webCab'), 'enlace viejo #contacto abre Nosotros › Contacto')
        ir(pg, '#guias')
        chk(vis(pg, 'guias') and not vis(pg, 'sistema'), 'enlace viejo #guias abre Programas › Programas')
        ir(pg, '#salud')
        chk(vis(pg, 'webEduSec') and not vis(pg, 'salud') and pg.locator('#webEdu .ed-fila').count() == 21, 'enlace viejo #salud abre la biblioteca de Educación (21 temas)')
        foto(pg, '103_web_educacion_' + n)
        pg.click('#webEdu .ed-fila[data-id=salud-sueno]'); pg.wait_for_timeout(400)
        chk('Sueño y Recuperación' in pg.inner_text('#webEdu') and pg.locator('#webEdu .ed-indice button').count() == 3, 'tema abierto en la web con índice')
        foto(pg, '104_web_tema_' + n)
        ir(pg, '#salud-ayuno')
        chk('Ayuno Intermitente' in pg.inner_text('#webEdu') and 'min de lectura' in pg.inner_text('#webEdu'), 'enlace a un tema (#salud-ayuno) lo abre directo')
        ir(pg, '#/programas/recetas')
        chk(vis(pg, 'recetas') and alto(pg) < 2200, 'Recetas sola: %d px' % alto(pg))
        ir(pg, '#/nosotros')
        chk(vis(pg, 'filosofia') and not vis(pg, 'comunidad'), 'Nosotros › Filosofía')
        pg.click('#nav .nav-logo'); pg.wait_for_timeout(400)
        chk(vis(pg, 'hero'), 'el logo regresa al inicio')
        pg.go_back(); pg.wait_for_timeout(400)
        chk(vis(pg, 'filosofia'), 'el botón atrás del navegador regresa a la sección anterior')
        chk(pg.evaluate("parseFloat(getComputedStyle(document.body).fontSize)") >= 16, 'texto base de 16 px')
        chk(not errs, 'sin errores de JavaScript ' + str(errs[:3]))
        pg.close()
    print('== app (no debe cambiar)')
    pa = b.new_page(viewport={'width': 390, 'height': 844}); ea = []
    pa.on('pageerror', lambda e: ea.append(str(e)))
    pa.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pa.add_init_script("if(!sessionStorage.x){sessionStorage.x=1;localStorage.setItem('aet_inicio',JSON.stringify({estado:'hecho'}));localStorage.setItem('aet_tour_visto','1');localStorage.setItem('aet_tour','1');localStorage.setItem('aet_nombre_pedido','1')}")
    pa.goto('http://localhost:8862/index.html?modo=app'); pa.wait_for_timeout(2400); pa.evaluate("try{aetCerrar()}catch(e){}")
    chk(not pa.evaluate("document.body.classList.contains('web-secciones')") and pa.query_selector('#webCab') is None, 'la app no carga el modo web')
    pa.click('.app-nav-btn[data-p=educacion]'); pa.wait_for_timeout(400)
    chk(pa.locator('#eduApp .ed-fila').count() == 21, 'Educación de la app sigue igual')
    pa.evaluate("abrirContenidoApp('productos','Tienda')"); pa.wait_for_timeout(500)
    chk(pa.is_visible('#appVisorContenido #productos') or pa.locator('#appVisorContenido .producto-card, #appVisorContenido [class*=prod]').count() > 0, 'la Tienda de la app sigue abriendo productos')
    chk(not ea, 'app sin errores de JavaScript ' + str(ea[:3]))
    b.close()
print('\n%d fallas' % len(bad) if bad else '\nTodo bien'); sys.exit(1 if bad else 0)
