# Prueba de la Trivia dentro de la app (sin servidor: la trivia es local y se sincroniza como el resto).
import subprocess, os, sys, json, time, atexit
from playwright.sync_api import sync_playwright
AQUI = os.path.dirname(os.path.abspath(__file__)); RAIZ = os.path.abspath(os.path.join(AQUI, '..', '..'))
CAP = os.path.join(AQUI, 'capturas'); os.makedirs(CAP, exist_ok=True)
web = subprocess.Popen(['python3', '-m', 'http.server', '8856'], cwd=RAIZ, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); atexit.register(web.terminate)
time.sleep(1)
bad = []
def chk(c, m):
    print(('  ok ' if c else '  ✗ ') + m)
    if not c: bad.append(m)
foto = lambda pg, n, full=False: pg.screenshot(path=os.path.join(CAP, n + '.png'), full_page=full)
TXT = lambda pg: pg.inner_text('#triviaApp')
def correcta(pg):
    return pg.evaluate("""() => { const q = document.getElementById('tvQ').textContent; for (const b in window.QB) for (const x of window.QB[b]) if (x[1] === q) {
        const ops = [...document.querySelectorAll('#tvOps .tv-op')]; return ops.findIndex(o => o.textContent.slice(1) === x[2]); } return -1; }""")
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx = b.new_context(service_workers='block', viewport={'width': 390, 'height': 844}); pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('dialog', lambda d: d.accept())
    pg.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pg.route('**/functions/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    pg.add_init_script("if(!sessionStorage.x){sessionStorage.x=1;localStorage.setItem('aet_inicio',JSON.stringify({estado:'hecho'}));localStorage.setItem('aet_tour_visto','1');localStorage.setItem('aet_tour','1');localStorage.setItem('aet_nombre_pedido','1')}")
    pg.goto('http://localhost:8856/index.html?modo=app'); pg.wait_for_timeout(2200); pg.evaluate("try{aetCerrar()}catch(e){}")
    print('1. Entrada desde Juegos')
    pg.evaluate("aetIr('juegos')"); pg.wait_for_timeout(400)
    chk(pg.is_visible('.jg-trivia') and 'Trivia Aeterion' in pg.inner_text('.jg-trivia'), 'tarjeta de Trivia en Juegos')
    pg.click('.jg-trivia'); pg.wait_for_timeout(900)
    t = TXT(pg)
    chk('Trivia Aeterion' in t and '180 preguntas' in t and 'Jugar nivel 1' in t, 'mapa de niveles con 180 preguntas')
    chk(pg.locator('.tv-nv').count() == 15 and pg.locator('.tv-nv.bloq').count() == 14, '15 niveles, 14 bloqueados')
    chk(pg.evaluate("document.querySelector('.app-nav-btn.activo').dataset.p") == 'juegos', 'Juegos queda resaltado en la barra')
    chk(pg.evaluate("[...document.scripts].some(s=>/arena|three/i.test(s.src))") is False, 'no carga nada del juego de peleas')
    foto(pg, '70_trivia_mapa', True)
    print('2. Nivel 1 perfecto')
    pg.click('[data-tv=jugar] >> nth=0'); pg.wait_for_timeout(500)
    chk(pg.is_visible('#tvQ') and 'pregunta 1 de 8' in TXT(pg).lower(), 'empieza el nivel')
    foto(pg, '71_trivia_pregunta')
    for i in range(8):
        k = correcta(pg); pg.wait_for_timeout(700)
        pg.click('#tvOps .tv-op >> nth=%d' % k); pg.wait_for_timeout(250)
        if i == 0: chk('¡Correcto!' in TXT(pg), 'marca correcto con explicación'); foto(pg, '72_trivia_correcta')
        pg.click('#tvSig'); pg.wait_for_timeout(250)
    t = TXT(pg)
    chk('Nivel 1 superado' in t and '★★★' in t and 'Desbloqueaste el nivel 2' in t, 'nivel superado con 3 estrellas')
    d = pg.evaluate("JSON.parse(localStorage.getItem('aet_trivia'))")
    chk(d['nivel'] == 2 and d['puntos'] > 1000 and d['estrellas'].get('1') == 3 and d['rayos'] == 3, 'avance guardado (nivel 2, puntos, rayos completos)')
    foto(pg, '73_trivia_fin')
    print('3. Fallar hasta quedarse sin energía')
    pg.click('[data-tv=jugar][data-l="2"]'); pg.wait_for_timeout(500)
    for i in range(3):
        k = correcta(pg); pg.wait_for_timeout(300)
        pg.click('#tvOps .tv-op >> nth=%d' % ((k + 1) % 4)); pg.wait_for_timeout(250)
        if i == 0: chk('Incorrecto · −1 rayo' in TXT(pg), 'error quita un rayo'); foto(pg, '74_trivia_error')
        pg.click('#tvSig'); pg.wait_for_timeout(300)
    t = TXT(pg)
    chk('Sin energía' in t and 'Perdiste el avance del nivel 2' in t, 'sin rayos: pierde el nivel')
    d = pg.evaluate("JSON.parse(localStorage.getItem('aet_trivia'))")
    chk(d['rayos'] == 0 and d['nivel'] == 2, 'rayos en 0, nivel 2 sigue desbloqueado')
    pg.click('[data-tv=mapa]'); pg.wait_for_timeout(400)
    chk('Recuperas 1 rayo cada 3 horas' in TXT(pg) and pg.query_selector('[data-tv=jugar]:not([disabled]).tv-btn') is None, 'mapa muestra la espera y no deja jugar')
    foto(pg, '75_trivia_sin_energia')
    print('4. Recupera rayos con el tiempo')
    pg.evaluate("const d=JSON.parse(localStorage.getItem('aet_trivia'));d.rayoT=Date.now()-7*3600e3;localStorage.setItem('aet_trivia',JSON.stringify(d))")
    pg.evaluate("aetIr('juegos')"); pg.wait_for_timeout(300)
    chk('Nivel 2' in pg.inner_text('.jg-trivia'), 'la tarjeta muestra tu nivel y puntos')
    pg.click('.jg-trivia'); pg.wait_for_timeout(500)
    d = pg.evaluate("JSON.parse(localStorage.getItem('aet_trivia'))")
    chk(d['rayos'] == 2 and 'Jugar nivel 2' in TXT(pg), '7 horas después: 2 rayos y puede jugar')
    print('5. Salir a mitad de nivel y botón atrás')
    pg.click('[data-tv=jugar] >> nth=0'); pg.wait_for_timeout(400)
    chk(pg.evaluate("triviaSub()") is True, 'dentro de un nivel')
    pg.click('[data-tv=salir]'); pg.wait_for_timeout(400)
    chk('Jugar nivel 2' in TXT(pg), 'salir regresa al mapa')
    print('6. Fusión entre dispositivos')
    r = pg.evaluate("triviaFusion({puntos:5000,nivel:6,estrellas:{1:2,5:3},mejor:{},t:1},{puntos:1200,nivel:2,estrellas:{1:3},mejor:{},rayos:1,t:2})")
    chk(r['puntos'] == 5000 and r['nivel'] == 6 and r['estrellas']['1'] == 3 and r['estrellas']['5'] == 3 and r['rayos'] == 1, 'combina avance (máximos) y rayos del más reciente')
    ctx2 = b.new_context(service_workers='block', viewport={'width': 1280, 'height': 860}); p2 = ctx2.new_page()
    p2.route('**/rest/v1/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{}'))
    p2.add_init_script("if(!sessionStorage.x){sessionStorage.x=1;localStorage.setItem('aet_inicio',JSON.stringify({estado:'hecho'}));localStorage.setItem('aet_tour_visto','1');localStorage.setItem('aet_tour','1');localStorage.setItem('aet_nombre_pedido','1')}")
    p2.goto('http://localhost:8856/index.html?modo=app&ir=trivia'); p2.wait_for_timeout(2600); p2.evaluate("try{aetCerrar()}catch(e){}")
    chk(p2.is_visible('#app-screen-trivia.activo') and 'Jugar nivel 1' in p2.inner_text('#triviaApp'), 'enlace directo ?ir=trivia')
    foto(p2, '76_trivia_pc')
    chk(not errs, 'sin errores de JavaScript ' + str(errs[:3]))
    b.close()
print('\n%d fallas' % len(bad) if bad else '\nTodo bien'); sys.exit(1 if bad else 0)
